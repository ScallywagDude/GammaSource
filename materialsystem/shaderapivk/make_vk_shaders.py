"""Writes materialsystem/shaderapivk/vkshaders.h: the SPIR-V for shaderapivk's shaders.

The HLSL is the DX11 backend's (rendershared.inl, s_szShader), so both renderers run the same
shader. It is compiled with Microsoft's DirectX Shader Compiler (github.com/microsoft/
DirectXShaderCompiler releases; the dxc in the Windows SDK has no SPIR-V output):

  py -3 materialsystem/shaderapivk/make_vk_shaders.py <path to dxc.exe>

Run materialsystem/shaderapivk/make_vk.py first so rendershared.inl here is current.
"""
import os, re, struct, subprocess, sys, tempfile

here = os.path.dirname(os.path.abspath(__file__))
dxc = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('DXC', 'dxc')

src = open(os.path.join(here, 'rendershared.inl')).read()
macro = re.search(r'#define GAMMA_SHADER_BINDINGS \\\n\t(".*")\n', src).group(1)
body = src[src.index('static const char s_szShader[] ='):]
body = body[:body.index(';\n')]
body = body.replace('GAMMA_SHADER_BINDINGS', macro)
# join the C string literals and undo their escapes
hlsl = ''.join(m.encode('latin-1').decode('unicode_escape') for m in re.findall(r'"((?:[^"\\]|\\.)*)"', body))

tmp = tempfile.mkdtemp()
path = os.path.join(tmp, 'gamma.hlsl')
open(path, 'w').write(hlsl)


def compile_stage(profile, entry):
    out = os.path.join(tmp, entry + '.spv')
    # DX cbuffer packing (the C++ constants struct follows it); entry points named main; HLSL 2018 as D3DCompile
    subprocess.run([dxc, '-spirv', '-T', profile, '-E', entry, '-fvk-use-dx-layout', '-fspv-entrypoint-name=main',
                    '-fspv-target-env=vulkan1.1', '-HV', '2018', '-O3', path, '-Fo', out], check=True)
    data = open(out, 'rb').read()
    return list(struct.unpack('<%dI' % (len(data) // 4), data))


def emit(name, words):
    lines = []
    for i in range(0, len(words), 8):
        lines.append('\t' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    return 'static const unsigned int %s[] =\n{\n%s\n};\n' % (name, '\n'.join(lines))


text = ('//========= GammaSource ============//\n//\n// GENERATED by materialsystem/shaderapivk/make_vk_shaders.py from rendershared.inl\'s\n'
        '// HLSL (the DX11 backend\'s shader) with dxc -spirv.\n//\n'
        '//=============================================================================//\n'
        '#ifndef VKSHADERS_H\n#define VKSHADERS_H\n#pragma once\n\n' +
        emit('g_VkVertexShader', compile_stage('vs_6_0', 'VSMain')) + '\n' +
        emit('g_VkFragmentShader', compile_stage('ps_6_0', 'PSMain')) + '\n#endif // VKSHADERS_H\n')
open(os.path.join(here, 'vkshaders.h'), 'w').write(text)
print('wrote', os.path.join(here, 'vkshaders.h'))
